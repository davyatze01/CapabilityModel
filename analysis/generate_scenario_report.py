def build_report_html(df: pd.DataFrame) -> str:
    scenario_blocks = []
    for scenario, entry in SCENARIO_READINGS.items():
        parts = [f"<h3>{entry['title']}</h3>"]
        if "intro" in entry:
            parts.append(f"<p>{entry['intro']}</p>")
            parts.append(render_parameters_table(entry["parameters"]))
        parts.append(f"<p><b>What changes vs. baseline</b>: {entry['what_changes']}</p>")
        parts.append(render_results_table(df, scenario))
        reading = entry["reading"]
        if len(reading) == 1:
            parts.append(f"<p><b>Reading</b>: {reading[0]}</p>")
        else:
            items = "".join(f"<li>{p}</li>" for p in reading)
            parts.append(f"<p><b>Reading</b> — multiple findings:</p><ol>{items}</ol>")
        scenario_blocks.append("\n".join(parts))

    return f"""<!doctype html>
<html><head><meta charset="utf-8"><title>Scenario Validation Report</title>
<style>{REPORT_CSS}</style></head>
<body>
<h1>Scenario Validation Report</h1>
<p>This report explains how each accessibility scenario is compared against baseline, what
statistical test establishes whether an observed difference is real and how to read the
results for each scenario. It documents the current hexagon-grid comparison and
significance-testing workflow.</p>
{STATIC_SECTIONS_HTML}
<h2>5. Per-scenario results</h2>
{"".join(scenario_blocks)}
{METHODOLOGICAL_NOTES_HTML}
</body></html>"""


def render_pdf(html: str, out_html: Path = OUT_HTML, out_pdf: Path = OUT_PDF) -> None:
    out_html.write_text(html, encoding="utf-8")
    print(f"[write] {out_html}")
    from weasyprint import HTML
    HTML(string=html, base_url=str(out_html.parent)).write_pdf(str(out_pdf))
    print(f"[write] {out_pdf}")


if __name__ == "__main__":
    df = load_significance_results()
    print(f"[load] {len(df)} rows from {SIGNIFICANCE_CSV}")
    print(df["scenario"].value_counts())
    stale = check_staleness(df)
    print("[staleness]", "some readings are stale -- see warnings above" if stale else "all readings match current data")
    html = build_report_html(df)
    render_pdf(html)
