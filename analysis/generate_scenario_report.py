STATIC_SECTIONS_HTML = """
<h2>1. What is being compared, in general</h2>
<p>Every scenario compares two or more <b>conditions</b> — a baseline plus one or more
alternatives — over the same set of roughly 1,568 hexagonal cells covering the study area.</p>
<p>The <b>baseline</b> is the run made without changing anything: the universal-traveler
setup, full transit feed, full mode set, standard affordability — the same conditions the
model already runs with by default. It is not itself a "finding"; it's the reference point
every other condition in a scenario is measured against. Each <b>alternative condition</b>
changes exactly one thing (or a clearly-scoped bundle of things — see each scenario's own
description in Section 5) relative to that same baseline: a bus service removed, a
neighbourhood's POIs removed, a new transit line added, a different traveler profile
simulated. Whatever difference shows up between baseline and an alternative condition is
attributable to that specific change, precisely because everything else about the run is
held identical to baseline.</p>
<p>Each condition's capability score is computed independently for every hexagon, then the
results are lined up so that each hexagon has one score per condition, side by side.</p>

<h2>2. Choosing a capability score: discrete bands vs. a continuous score</h2>
<p>The model's production output places every hexagon into one of five ordered capability
bands (very low through very high) and reports the band's midpoint value. That is the right
choice for presenting results on a map, but it is a poor choice for detecting change
statistically: two hexagons that both remain in the "medium" band register as zero
difference even if one moved much closer to the boundary than the other, and the
significance test used here treats exact-zero differences as uninformative and discards
them. If most hexagons don't fully cross a band boundary, most of the sample ends up
contributing nothing to the test.</p>
<p>To avoid discarding real, sub-band movement, this analysis uses a continuous version of
the same underlying score instead: the smooth outranking credibility that the banding
procedure computes internally, before it collapses everything into five bands. It uses the
same concordance/discordance/veto logic as the production score, without the final rounding
step. It is not a different measure of accessibility, only a higher-resolution readout of
the same one. This continuous mode is opt-in. It never affects the model's normal
(production) output. Every result in this report was generated with it turned on.</p>

<h2>3. Baseline test: paired Wilcoxon signed-rank test</h2>
<p>For every (scenario, capability, condition) combination, the analysis:</p>
<ol>
<li>Keeps only hexagons that have valid data on both sides of the comparison.</li>
<li>Computes the paired difference in score between the two conditions, hexagon by
hexagon.</li>
<li>Runs a paired Wilcoxon signed-rank test on those differences. The null hypothesis is
that there is no systematic shift between the two conditions — i.e., that the paired
differences are symmetric around zero.</li>
<li>Estimates an effect size via a bootstrap 95% confidence interval on the
<b>median</b> difference (2,000 resamples).</li>
</ol>

<h2>4. Correction: spatial block sign-flip permutation test</h2>
<p>To account for the fact that nearby hexagons are not independent, a second,
spatially-aware test is run alongside the naive Wilcoxon test, following the block/cluster
permutation approach that is standard practice in spatial statistics and neuroimaging when
observations are geographically correlated:</p>
<ol>
<li><b>Group nearby hexagons into blocks.</b> Each hexagon is assigned to a roughly 500m
&times; 500m spatial cell based on its location; hexagons that land in the same cell form
one block. This block size is a tunable sensitivity parameter, not something fit to the
data — a sanity check is to confirm the resulting number of blocks is neither implausibly
small (over-correcting) nor close to the number of hexagons (no different from treating them
as independent).</li>
<li><b>Test statistic.</b> The same signed-rank information the Wilcoxon test uses is
combined into a single summary number for the whole comparison.</li>
<li><b>Permutation.</b> Many times over (thousands of repetitions), every hexagon in a
given block has its sign randomly and simultaneously flipped — never hexagon-by-hexagon —
and the test statistic is recomputed. This is the core of the correction: under this
resampling, correlated neighbours move together exactly as they would under a genuine,
spatially clustered effect, instead of having that correlation averaged away as if it
didn't exist.</li>
<li><b>Empirical significance.</b> The observed test statistic is compared against the
distribution of statistics produced by all those random permutations; the p-value is the
fraction of permutations that were as extreme or more extreme than what was actually
observed. Running more permutations lowers the smallest p-value the test can report (2,000
permutations bottoms out around 0.0005; 50,000 pushes that down to about 0.00002).</li>
<li><b>Correcting for testing many things at once.</b> Because this analysis runs many
such tests in a single report (three capabilities &times; several conditions per scenario),
a standard multiple-comparison correction (Benjamini-Hochberg) is applied across all of
them, for both the naive and the spatially-corrected p-values.</li>
</ol>
"""

