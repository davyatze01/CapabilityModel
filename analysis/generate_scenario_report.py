def _fmt_pct(x: float) -> str:
    return f"{x:.1f}%"


def _fmt_p(x: float) -> str:
    return "&lt; 0.0005" if x < 0.0005 else f"{x:.4f}"


def render_results_table(df: pd.DataFrame, scenario: str) -> str:
    """One row per (capability, comparison) for `scenario`, capabilities in CAPABILITIES
    order, comparisons in the order significance_analysis.R wrote them (already the
    baseline-first / multi-arm order the original report used). Uniform columns across
    every scenario -- a deliberate simplification vs. the original hand-authored report's
    per-scenario varying column set (e.g. new-metro dropped the CI column)."""
    sub = df[df["scenario"] == scenario]
    rows_html = []
    for capability in CAPABILITIES:
        for _, row in sub[sub["capability"] == capability].iterrows():
            rows_html.append(
                "<tr>"
                f"<td>{capability}</td>"
                f"<td>{row['group_a']} &rarr; {row['group_b']}</td>"
                f"<td>{int(row['n_hexagons'])}</td>"
                f"<td>{int(row['n_changed'])}</td>"
                f"<td>{_fmt_pct(row['pct_changed'])}</td>"
                f"<td>{row['median_diff']:+.3f}</td>"
                f"<td>[{row['ci_low']:+.3f}, {row['ci_high']:+.3f}]</td>"
                f"<td>{_fmt_p(row['p_value_block_perm'])}</td>"
                f"<td>{int(row['n_blocks'])}</td>"
                "</tr>"
            )
    return (
        "<table><thead><tr>"
        "<th>capability</th><th>comparison</th><th>n hex</th><th>n changed</th>"
        "<th>% changed</th><th>median &Delta;</th><th>95% CI</th>"
        "<th>p (block-perm)</th><th>n blocks</th>"
        "</tr></thead><tbody>" + "".join(rows_html) + "</tbody></table>"
    )


def render_parameters_table(parameters: dict[str, tuple[str, str, str]]) -> str:
    """elder-student's baseline/student/elderly persona-parameter table (Section 5.4 only)."""
    rows_html = "".join(
        f"<tr><td>{param}</td><td>{baseline}</td><td>{student}</td><td>{elderly}</td></tr>"
        for param, (baseline, student, elderly) in parameters.items()
    )
    return (
        "<table><thead><tr><th>parameter</th><th>baseline</th><th>student</th>"
        "<th>elderly</th></tr></thead><tbody>" + rows_html + "</tbody></table>"
    )


def load_significance_results(path: Path = SIGNIFICANCE_CSV) -> pd.DataFrame:
    if not path.exists():
        raise FileNotFoundError(
            f"{path} not found -- run analysis/significance_analysis.R first "
            "(requires R; not available on this machine)."
        )
    return pd.read_csv(path)


def check_staleness(df: pd.DataFrame) -> bool:
    """Compare each reading's recorded reading_basis against the live CSV. Prints a warning
    per drifted/missing comparison. Returns True if anything is stale (or missing), so the
    caller can decide whether to still render the report or stop and ask for updated readings.
    """
    any_stale = False
    for scenario, entry in SCENARIO_READINGS.items():
        sub = df[df["scenario"] == scenario]
        for (capability, group_a, group_b), expected in entry.get("reading_basis", {}).items():
            row = sub[
                (sub["capability"] == capability)
                & (sub["group_a"] == group_a)
                & (sub["group_b"] == group_b)
            ]
            if row.empty:
                print(f"[stale] {scenario}/{capability}/{group_a}->{group_b}: "
                      f"no matching row in {SIGNIFICANCE_CSV} -- reading has no current data.")
                any_stale = True
                continue
            actual = float(row["median_diff"].iloc[0])
            if abs(actual - expected) > STALENESS_TOLERANCE:
                print(f"[stale] {scenario}/{capability}/{group_a}->{group_b}: "
                      f"reading written against median_diff={expected:g}, "
                      f"current value is {actual:g} (drift {abs(actual - expected):g} "
                      f"> tolerance {STALENESS_TOLERANCE:g}) -- reading needs review.")
                any_stale = True
    return any_stale


